package NeonAffect;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.DirectoryStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes data/behavior_catalogue.csv: one row per behaviour plan, as a READ-ONLY REPORT.
 *
 * The capabilities' template lines are the single source of truth:
 * <pre>
 *     #uses BehaviorPlan&lt;AffectEnum.RAGE, AffectEnum.VERBAL&gt; ScreamPlan;
 * </pre>
 * This class only reads them (plus the active formula from data/cojack_cognitive.xml and the
 * MBTI tags recorded in data/added_behaviors.csv and data/new_emotion_behaviors.csv) and writes
 * the catalogue. NOTHING reads the catalogue back: editing it changes nothing, and the next
 * build overwrites it. The file is marked read-only after writing.
 *
 * build.bat runs this as its last step. Run by hand: java -cp . NeonAffect.BehaviorCatalogue
 */
public final class BehaviorCatalogue {
    private BehaviorCatalogue() {
    }

    private static final String CAPABILITIES = "NeonAffect";
    private static final String XML = "data/cojack_cognitive.xml";
    private static final String OUT = "data/behavior_catalogue.csv";
    private static final String[] TAG_FILES = {"data/added_behaviors.csv", "data/new_emotion_behaviors.csv"};

    private static final Pattern LINE = Pattern.compile(
        "#uses\\s+BehaviorPlan\\s*<\\s*AffectEnum\\.(\\w+)\\s*,\\s*AffectEnum\\.(\\w+)\\s*>\\s+(\\w+)\\s*;");

    public static void main(String[] args) throws Exception {
        Map<String, String> formulas = activeFormulas();
        Map<String, String> tags = mbtiTags();

        // affect name -> rows, sorted by affect name, then channel order, then plan
        TreeMap<String, List<String>> byAffect = new TreeMap<String, List<String>>();
        int rows = 0;
        try (DirectoryStream<Path> caps = Files.newDirectoryStream(Paths.get(CAPABILITIES), "*.cap")) {
            for (Path p : caps) {
                String src = new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
                Matcher m = LINE.matcher(src);
                while (m.find()) {
                    int affect = AffectEnum.class.getField(m.group(1)).getInt(null);
                    String affectName = AffectEnum.GetName(affect);
                    String channel = (String) AffectEnum.class.getField(m.group(2)).get(null);
                    String plan = m.group(3);
                    String formula = formulas.get("Neon" + affectName + channel + "|" + plan);
                    String t = tags.get(plan);
                    String row = String.join(",",
                        affectName,
                        channel,
                        plan,
                        behaviour(plan, affectName),
                        formula == null ? "" : formula,
                        t == null ? ",," : t,
                        t == null ? "converted" : "added");
                    String key = affectName;
                    List<String> l = byAffect.get(key);
                    if (l == null) {
                        l = new ArrayList<String>();
                        byAffect.put(key, l);
                    }
                    l.add(channelOrder(channel) + "|" + plan + "|" + row);
                    rows++;
                }
            }
        }

        StringBuilder out = new StringBuilder();
        out.append("# GENERATED by NeonAffect.BehaviorCatalogue at every build - a READ-ONLY REPORT.\n");
        out.append("# Nothing reads this file; editing it changes nothing and the next build overwrites it.\n");
        out.append("# Source of truth: the #uses BehaviorPlan<...> lines in NeonAffect\\*AffectCapability.cap.\n");
        out.append("# formula = active PLAN_VALUE formula in the plan's own channel group of data\\cojack_cognitive.xml\n");
        out.append("# EI/TF/JP = MBTI tags (recorded only for plans added from 2026-10-07; empty for converted ones)\n");
        out.append("affect,channel,plan,behaviour,formula,EI,TF,JP,origin\n");
        for (List<String> l : byAffect.values()) {
            l.sort(null);
            for (String s : l) {
                out.append(s.substring(s.indexOf('|', s.indexOf('|') + 1) + 1)).append('\n');
            }
        }

        File f = new File(OUT);
        if (f.exists() && !f.canWrite()) {
            f.setWritable(true);
        }
        Files.write(f.toPath(), out.toString().getBytes(StandardCharsets.UTF_8));
        f.setReadOnly();
        System.out.println("BehaviorCatalogue: " + rows + " behaviour plans, " + byAffect.size()
            + " affects -> " + OUT + " (read-only report)");
    }

    /** "Neon<Affect><Channel>|<plan>" -> the plan's formula in that group's moderator. */
    private static Map<String, String> activeFormulas() throws IOException {
        Map<String, String> out = new HashMap<String, String>();
        String xml = new String(Files.readAllBytes(Paths.get(XML)), StandardCharsets.UTF_8);
        Matcher g = Pattern.compile("<parameter_group name=\"(Neon\\w+?)\">(.*?)</parameter_group>", Pattern.DOTALL).matcher(xml);
        while (g.find()) {
            Matcher a = Pattern.compile("<applies_to attribute=\"(\\w+)\" name=\"PLAN_VALUE\" formula=\"([^\"]*)\"/>").matcher(g.group(2));
            while (a.find()) {
                out.put(g.group(1) + "|" + a.group(1), a.group(2));
            }
        }
        return out;
    }

    /** plan -> "EI,TF,JP" from the recorded tag lists. */
    private static Map<String, String> mbtiTags() throws IOException {
        Map<String, String> out = new HashMap<String, String>();
        for (String file : TAG_FILES) {
            Path p = Paths.get(file);
            if (!Files.exists(p)) {
                continue;
            }
            for (String line : Files.readAllLines(p, StandardCharsets.UTF_8)) {
                if (line.startsWith("#") || line.startsWith("plan,") || line.trim().isEmpty()) {
                    continue;
                }
                String[] f = line.trim().split(",");
                if (f.length >= 6) {
                    out.put(f[0], f[3] + "," + f[4] + "," + f[5]);
                }
            }
        }
        return out;
    }

    /** "ScreamRagePlan" -> "Scream"; "ScreamPlan" -> "Scream". */
    private static String behaviour(String plan, String affectName) {
        String b = plan.endsWith("Plan") ? plan.substring(0, plan.length() - 4) : plan;
        if (b.endsWith(affectName) && b.length() > affectName.length()) {
            b = b.substring(0, b.length() - affectName.length());
        }
        return b;
    }

    private static int channelOrder(String channel) {
        if (channel.equals(AffectEnum.VERBAL)) {
            return 0;
        }
        if (channel.equals(AffectEnum.NONVERBAL)) {
            return 1;
        }
        return 2;
    }
}
